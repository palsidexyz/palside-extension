import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { contractsRoot, requireDependencies, root, run } from './tools.mjs';

requireDependencies();
run('forge', ['build', '--no-cache']);
const contracts = { MockPALS: 'mockPalsAbi', PalsideRedPacket: 'redPacketAbi' };
const sources = ['contracts/foundry.toml', 'contracts/dependencies.json', ...Object.keys(contracts).map(name => `contracts/src/${name}.sol`)];
const sourceDigests = Object.fromEntries(await Promise.all(sources.map(async file => [file, createHash('sha256').update(await readFile(path.join(root, file))).digest('hex')])));
let output = '// Generated by scripts/chain/generate.mjs from Foundry artifacts. Do not edit.\n\n';
for (const [name, symbol] of Object.entries(contracts)) {
  const artifact = JSON.parse(await readFile(path.join(contractsRoot, `out/${name}.sol/${name}.json`), 'utf8'));
  output += `export const ${symbol} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
output += `export const contractSourceDigests = ${JSON.stringify(sourceDigests, null, 2)} as const;\n`;
const destination = path.join(root, 'packages/shared/src/chain/generated.ts');
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('Generated contract ABI is stale; run npm run chain:generate');
  console.log('Generated ABI matches Foundry artifacts');
} else {
  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, output);
  console.log('Generated shared contract ABI');
}
